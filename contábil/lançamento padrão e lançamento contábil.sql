select
	CT2.CT2_CREDIT,
	CT2.CT2_LP,
	CT2.CT2_SEQLAN,
	CT5.CT5_LANPAD,
	CT5.CT5_SEQUENC,
	CT5.CT5_CREDIT
from CT5010 as CT5 (nolock)
	inner join CT2010 as CT2
		on CT2.D_E_L_E_T_ = ''
		and CT5.CT5_FILIAL + CT5.CT5_LANPAD + CT5.CT5_SEQUEN = CT2.CT2_FILIAL + CT2.CT2_LANPAD + CT2.CT2_SEQUEN
where
		CT5.D_E_L_E_T_ = ''
	and CT2.CT2_LP in ('610', '620')