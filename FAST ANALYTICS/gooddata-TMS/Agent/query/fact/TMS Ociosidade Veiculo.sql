SELECT DISTINCT 'P |01|01' AS BK_EMPRESA,
                CASE
                    WHEN DTW_FILIAL IS NULL THEN 'P |01||'
                    ELSE 'P |01|01'+ CAST(DTW_FILIAL AS CHAR (6))
                END AS BK_FILIAL,
                DTW.DTW_FILORI AS FILIAL_ORIGEM,
                DTW.DTW_VIAGEM AS NUMERO_VIAGEM,
                'P |01|DA3010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DA3CAVALO.DA3_FILIAL, ' '))+'|'+RTRIM(COALESCE(DTR.DTR_CODVEI, ' ')), ' '), '|') AS CODIGO_CAVALO,
                'P |01|DA3010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DA3REBOQUE1.DA3_FILIAL, ' '))+'|'+RTRIM(COALESCE(DTR.DTR_CODRB1, ' ')), ' '), '|') AS CODIGO_REBOQUE1,
                'P |01|DA3010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DA3REBOQUE2.DA3_FILIAL, ' '))+'|'+RTRIM(COALESCE(DTR.DTR_CODRB2, ' ')), ' '), '|') AS CODIGO_REBOQUE2,
                'P |01|DA3010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DA3REBOQUE3.DA3_FILIAL, ' '))+'|'+RTRIM(COALESCE(DTR.DTR_CODRB3, ' ')), ' '), '|') AS CODIGO_REBOQUE3,

  (SELECT TOP(1) CASE
                     WHEN DTW_DATREA = ' ' THEN ' '
                     ELSE CONCAT(CONVERT(DATE,DTW_DATREA), ' ', DTW_HORREA)
                 END
   FROM DTW010 DTWH
   WHERE DTW_FILORI = DTW.DTW_FILORI
     AND DTW_VIAGEM = DTW.DTW_VIAGEM
     AND DTW_ATIVID = '049'
     AND DTW_CODCLI = ' '
     AND DTW_LOJCLI = ' '
     AND DTWH.D_E_L_E_T_ = ' ' ) AS 'DATAHORASAIDA',

  (SELECT TOP(1) CASE
                     WHEN DTW_DATREA = ' ' THEN ' '
                     ELSE CONCAT(CONVERT(DATE,DTW_DATREA), ' ', DTW_HORREA)
                 END
   FROM DTW010 DTWH
   WHERE DTW_FILORI = DTW.DTW_FILORI
     AND DTW_VIAGEM = DTW.DTW_VIAGEM
     AND DTW_ATIVID = '050'
     AND DTW_CODCLI = ' '
     AND DTW_LOJCLI = ' '
     AND DTWH.D_E_L_E_T_ = ' ' ) AS 'DATAHORACHEGADA',<<CODE_INSTANCE>> AS INSTANCIA
FROM DTW010 DTW
INNER JOIN DTR010 DTR ON DTR.DTR_FILIAL = DTW_FILIAL
AND DTR.DTR_FILORI = DTW.DTW_FILORI
AND DTR.DTR_VIAGEM = DTW.DTW_VIAGEM
AND DTR.D_E_L_E_T_ = ' '
INNER JOIN DA3010 DA3CAVALO ON DA3CAVALO.DA3_FILIAL = '      '
AND DA3CAVALO.DA3_COD = DTR.DTR_CODVEI
AND DA3CAVALO.D_E_L_E_T_ = ' '
LEFT JOIN DA3010 DA3REBOQUE1 ON DA3REBOQUE1.DA3_FILIAL = '      '
AND DA3REBOQUE1.DA3_COD = DTR.DTR_CODRB1
AND DA3REBOQUE1.D_E_L_E_T_ = ' '
LEFT JOIN DA3010 DA3REBOQUE2 ON DA3REBOQUE2.DA3_FILIAL = '      '
AND DA3REBOQUE2.DA3_COD = DTR.DTR_CODRB2
AND DA3REBOQUE2.D_E_L_E_T_ = ' '
LEFT JOIN DA3010 DA3REBOQUE3 ON DA3REBOQUE3.DA3_FILIAL = '      '
AND DA3REBOQUE3.DA3_COD = DTR.DTR_CODRB3
AND DA3REBOQUE3.D_E_L_E_T_ = ' '
WHERE DTW_DATREA BETWEEN <<START_DATE>> AND <<FINAL_DATE>>
  AND DTW.DTW_CODCLI = ' '
  AND DTW.DTW_LOJCLI = ' '
  AND DTW.DTW_ATIVID IN ('050',
                         '049')
  AND DTW.D_E_L_E_T_ = ' '