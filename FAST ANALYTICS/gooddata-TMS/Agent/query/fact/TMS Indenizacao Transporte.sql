SELECT 'P |01|01' AS BK_EMPRESA,
       CASE
           WHEN DUB_FILIAL IS NULL THEN 'P |01||'
           ELSE 'P |01|01'+ CAST(DUB_FILIAL AS CHAR (8))
       END AS BK_FILIAL,
       DUB.DUB_DATRID AS DATA_REGISTRO,
       DUB.DUB_HORRID AS HORA_REGISTRO,
       DUB.DUB_ITEM AS ITEM,
       DUB.DUB_FILRID AS FILIAL_REGISTRO,
       DUB.DUB_NUMRID AS NUMERO_REGISTRO,
       'P |01|DU3010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DU3.DU3_FILIAL, ' '))+'|'+RTRIM(COALESCE(DUB.DUB_COMSEG, ' ')), ' '), '|') AS RAMO_SEGURO,
       'P |01|DT2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DT2.DT2_FILIAL, ' '))+'|'+RTRIM(COALESCE(DUB.DUB_CODOCO, ' ')), ' '), '|') AS BK_CODIGO_OCORRENCIA,
       DUB.DUB_NUMPRO AS NUMERO_PROCESSO,
       'P |01|DUY010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYORI.DUY_FILIAL, ' '))+'|'+RTRIM(COALESCE(DT6_CDRORI, ' ')), ' '), '|') AS BK_CDRORI,
       'P |01|DUY010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYDES.DUY_FILIAL, ' '))+'|'+RTRIM(COALESCE(DT6_CDRDES, ' ')), ' '), '|') AS BK_CDRDES,
       'P |'+ COALESCE(NULLIF(RTRIM(COALESCE(DUB_STATUS, ' ')), ' '), '|') AS BK_STATUS_INDENIZACAO,
       'P |01|SA1010|'+ COALESCE(NULLIF(RTRIM(COALESCE(SA1.A1_FILIAL, ' '))+'|'+RTRIM(COALESCE(DUB_CODCLI, ' '))+RTRIM(COALESCE(DUB_LOJCLI, ' ')), ' '), '|') AS BK_CLIENTE,
       DUB.DUB_QTDOCO AS QUANTIDADE_OCORRENCIA,
       DUB.DUB_VALPRE AS VALOR_PREJUIZO,
       DUB.DUB_VALIND AS VALOR_INDENIZADO,
       DUB.DUB_DATVEN AS DATA_VENCIMENTO,
       DUB.DUB_DATENC AS DATA_ENCERRAMENTO,
       DUB_FILDOC AS BK_FILIAL_DOCTO,
       DUB_DOC AS BK_NUMERO_DOCUMENTO,
       DUB_SERIE AS BK_SERIE,
       'P |'+ COALESCE(NULLIF(RTRIM(COALESCE(DUB_STATUS, ' ')), ' '), '|') AS BK_STATUS,
       'P |'+ COALESCE(NULLIF(RTRIM(COALESCE(DT6_DOCTMS, ' ')), ' '), '|') AS BK_DOCTMS,
       'P |'+ COALESCE(NULLIF(RTRIM(COALESCE(DT6_TIPTRA, ' ')), ' '), '|') AS BK_TIPTRA,
       'P |'+ COALESCE(NULLIF(RTRIM(COALESCE(DT2_RESOCO, ' ')), ' '), '|') AS RESPONSAVEL_OCORRENCIA,
       CASE
           WHEN SA1.A1_COD_MUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(SA1.A1_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(SA1.A1_EST, ' '))+RTRIM(COALESCE(SA1.A1_COD_MUN, ' ')), ' '), '|')
       END AS BK_REGIAO_CLI,
       CASE
           WHEN REM.A1_COD_MUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(REM.A1_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(REM.A1_EST, ' '))+RTRIM(COALESCE(REM.A1_COD_MUN, ' ')), ' '), '|')
       END AS BK_REGIAO_REM,
       CASE
           WHEN DES.A1_COD_MUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DES.A1_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DES.A1_EST, ' '))+RTRIM(COALESCE(DES.A1_COD_MUN, ' ')), ' '), '|')
       END AS BK_REGIAO_DES,
       CASE
           WHEN DEV.A1_COD_MUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DEV.A1_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DEV.A1_EST, ' '))+RTRIM(COALESCE(DEV.A1_COD_MUN, ' ')), ' '), '|')
       END AS BK_REGIAO_DEV,
       CASE
           WHEN DUYCAL.DUY_CODMUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYCAL.DUY_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYCAL.DUY_EST, ' '))+RTRIM(COALESCE(DUYCAL.DUY_CODMUN, ' ')), ' '), '|')
       END AS BK_REGIAO_CDRCAL,
       CASE
           WHEN DUYORI.DUY_CODMUN = ' ' THEN 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYORI.DUY_EST, ' ')), ' '), '|')
           ELSE 'P |01|CC2010|'+ COALESCE(NULLIF(RTRIM(COALESCE(DUYORI.DUY_EST, ' '))+RTRIM(COALESCE(DUYORI.DUY_CODMUN, ' ')), ' '), '|')
       END AS BK_REGIAO_CDRORI
FROM DUB010 DUB
INNER JOIN DT6010 DT6 ON DT6.DT6_FILIAL = '      '
AND DT6.DT6_FILDOC = DUB.DUB_FILDOC
AND DT6.DT6_DOC = DUB.DUB_DOC
AND DT6.DT6_SERIE = DUB.DUB_SERIE
LEFT JOIN DU3010 DU3 ON DU3.DU3_FILIAL = '      '
AND DU3.DU3_COMSEG = DUB.DUB_COMSEG
AND DU3.D_E_L_E_T_ = ' '
LEFT JOIN DT2010 DT2 ON DT2.DT2_FILIAL = '      '
AND DT2.DT2_CODOCO = DUB.DUB_CODOCO
AND DT2.D_E_L_E_T_ = ' '
LEFT JOIN SA1010 SA1 ON SA1.A1_FILIAL = '      '
AND SA1.A1_COD = DUB.DUB_CODCLI
AND SA1.A1_LOJA = DUB.DUB_LOJCLI
AND SA1.D_E_L_E_T_ = ' '
LEFT JOIN DUY010 DUYORI ON DUYORI.DUY_FILIAL = DT6_FILIAL
AND DUYORI.DUY_GRPVEN = DT6.DT6_CDRORI
AND DUYORI.D_E_L_E_T_ = ' '
LEFT JOIN DUY010 DUYDES ON DUYDES.DUY_FILIAL = DT6_FILIAL
AND DUYDES.DUY_GRPVEN = DT6.DT6_CDRDES
AND DUYDES.D_E_L_E_T_ = ' '
LEFT JOIN DUY010 DUYCAL ON DUYCAL.DUY_FILIAL = DT6_FILIAL
AND DUYCAL.DUY_GRPVEN = DT6.DT6_CDRDES
AND DUYCAL.D_E_L_E_T_ = ' '
LEFT JOIN SA1010 REM ON REM.A1_FILIAL = '      '
AND REM.A1_COD = DT6.DT6_CLIREM
AND REM.A1_LOJA = DT6.DT6_LOJREM
AND REM.D_E_L_E_T_ = ' '
LEFT JOIN SA1010 DES ON DES.A1_FILIAL = '      '
AND DES.A1_COD = DT6.DT6_CLIDES
AND DES.A1_LOJA = DT6.DT6_LOJDES
AND DES.D_E_L_E_T_ = ' '
LEFT JOIN SA1010 DEV ON DEV.A1_FILIAL = '      '
AND DEV.A1_COD = DT6.DT6_CLIDEV
AND DEV.A1_LOJA = DT6.DT6_LOJDEV
AND DEV.D_E_L_E_T_ = ' '
LEFT JOIN DDB010 DDB ON DDB.DDB_FILIAL = DT6_FILIAL
AND DDB.DDB_CODNEG = DT6.DT6_CODNEG
AND DDB.D_E_L_E_T_ = ' '
INNER JOIN SX5010 SX5 ON SX5.X5_FILIAL = '      ' /*SUBSTRING(DT6_FILIAL, 1, 5) + SUBSTRING(X5_FILIAL, 6, 8)*/
AND SX5.X5_TABELA = 'L4'
AND SX5.X5_CHAVE = DT6.DT6_SERVIC
AND SX5.D_E_L_E_T_ = ' '
WHERE DUB.DUB_DATRID BETWEEN <<START_DATE>> AND <<FINAL_DATE>>
  AND DUB.D_E_L_E_T_ = ' '