select
    SAK010.AK_FILIAL,
    SAK010.AK_COD,
    SCR010.CR_LIBAPRO,
    SCR010.CR_FILIAL,
    SCR010.CR_NUM,
    SCR010.CR_NIVEL,
    max(SCR010.CR_NIVEL) as NIVEL_MAX,
    'P |01|SAK010|'+ COALESCE(NULLIF(RTRIM(COALESCE(SAK010.AK_FILIAL, ' '))+'|'+RTRIM(COALESCE(SAK010.AK_COD, ' ')), ' '), '|') as BK_APROVADOR
from SCR010
    inner join SAK010
        on SAK010.D_E_L_E_T_ = ''
        and SAK010.AK_COD = SCR010.CR_LIBAPRO
where
        SCR010.D_E_L_E_T_ = ''
    and SCR010.CR_TIPO = 'PC'
group by
    SAK010.AK_FILIAL,
    SAK010.AK_COD,
    SCR010.CR_LIBAPRO,
    SCR010.CR_FILIAL,
    SCR010.CR_NUM,
    SCR010.CR_NIVEL
