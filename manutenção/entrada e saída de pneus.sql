select
	TR7.TR7_FILIAL,
	TR7.TR7_LOTE,
	TR7.TR7_DTLOTE,
	TR7.TR7_HRLOTE,
	TR7.TR7_SERVIC,
	SD1.D1_DOC,
	SD1.D1_SERIE,
	SD1.D1_FORNECE,
	SD1.D1_LOJA,
	SD1.D1_OP,
	TR8.TR8_ORDEM,
	TR8.TR8_CODBEM,

	TR8.TR8_MEDIDA,
	TR8.TR8_TIPMOD,
	TR8.TR8_BANDA,
	TR8.TR8_VALOR,
	TR8.TR8_MOTIVO,

	TR7.TR7_DTRECI,
	TR7.TR7_HRRECI

from TR7010 TR7 (nolock)
	inner join TR8010 TR8 (nolock)
		on TR8.D_E_L_E_T_ = ''
		and TR8.TR8_FILIAL = TR7.TR7_FILIAL
		and TR8.TR8_LOTE = TR7.TR7_LOTE
	left join SD1010 SD1 (nolock)
		on SD1.D_E_L_E_T_ = ''
		and cast(SD1.D1_DOC as int) = TR7.TR7_NFE
		and cast(SD1.D1_SERIE as int) = TR7.TR7_SERIE
		and SD1.D1_FORNECE = TR7.TR7_FORNEC
		and SD1.D1_LOJA = TR7.TR7_LOJA
where
		TR7.D_E_L_E_T_ = ''
