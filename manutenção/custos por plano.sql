select
	STJ010.TJ_FILIAL,
	ST5010.T5_CODBEM,
	STL010.TL_ORDEM,
	STJ010.TJ_PLANO,
	ST4010.T4_NOME,
	ST5010.T5_DESCRIC,
	ST5010.T5_SEQRELA,
	STL010.TL_QUANTID,
	STL010.TL_CUSTO,
	STL010.TL_DTINICI,
	STL010.TL_DTFIM,
	STL010.TL_HOINICI,
	STL010.TL_HOFIM,
	STJ010.TJ_DTMRINI,
	STJ010.TJ_DTMRFIM,

	row_number() over
	(
		partition by
			STL010.TL_FILIAL,
			ST5010.T5_CODBEM,
			STL010.TL_ORDEM,
			STJ010.TJ_PLANO,
			ST4010.T4_SERVICO,
			ST4010.T4_NOME,
			STL010.TL_TAREFA,
			ST5010.T5_SEQRELA,
			STL010.TL_DTINICI,
			STL010.TL_DTFIM,
			STL010.TL_HOINICI,
			STL010.TL_HOFIM,
			STJ010.TJ_DTMRINI,
			STJ010.TJ_DTMRFIM
		order by
			STL010.TL_FILIAL,
			ST5010.T5_CODBEM,
			STL010.TL_ORDEM
	) as contador
from STJ010 (nolock)
	inner join STL010 (nolock)
		on STL010.TL_FILIAL = STJ010.TJ_FILIAL
		and STL010.TL_ORDEM = STJ010.TJ_ORDEM
		and STL010.TL_PLANO = STJ010.TJ_PLANO

		inner join ST5010 (nolock)
			on ST5010.T5_TAREFA = STL010.TL_TAREFA

	inner join ST4010(nolock)
		on ST4010.T4_SERVICO = STJ010.TJ_SERVICO


SELECT * FROM STL010 WHERE TL_ORDEM = '004702' AND TL_TAREFA = 6281
