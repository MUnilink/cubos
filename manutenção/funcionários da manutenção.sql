select
	ST1.T1_FILIAL as FILIAL,
	ST1.T1_CODFUNC as CODIGO,
	ST1.T1_NOME as NOME,
	ST1.T1_CCUSTO as CC,
    (select trim(CTT010.CTT_DESC01) from CTT010 where CTT010.D_E_L_E_T_ = '' and CTT010.CTT_CUSTO = ST1.T1_CCUSTO) as CCUSTO,
	ST1.T1_TURNO as COD_TURNO,
    (select trim(SH7010.H7_DESCRI) from SH7010 where SH7010.D_E_L_E_T_ = '' and SH7010.H7_CODIGO = ST1.T1_TURNO) as DESC_TURNO,
	ST1.T1_DISPONI as DISPONIVEL,
	ST1.T1_TIPOFUN as TIPOFUN,
	ST1.T1_EMAIL as EMAIL
from ST1010 ST1 (nolock)
where ST1.D_E_L_E_T_ = ''
