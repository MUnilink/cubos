select
	STJ010.TJ_FILIAL as FILIAL,
	STJ010.TJ_ORDEM as NUM_OS,
	SCP010.CP_OP as NUM_OP,
	SCP010.CP_NUM as NUM_SA,
	SCP010.CP_ITEM as ITEM_SA,

	SCP010.CP_PRODUTO as COD_PRODUTO,
	SCP010.CP_DESCRI as PRODUTO,
	SCP010.CP_SOLICIT as SOLICITANTE,
	SCP010.CP_EMISSAO as DATA_SA,
	STJ010.TJ_DTORIGI as DATA_OS,

	SCP010.CP_QUANT as QTD_SOLICITADA,
	SCP010.CP_QUJE as QTD_ATENDIDA,

	row_number() over
	(
		partition by
			STJ010.TJ_FILIAL,
			STJ010.TJ_ORDEM,
			SCP010.CP_OP,
			SCP010.CP_NUMOS,
			SCP010.CP_NUM,
			SCP010.CP_ITEM

		order by
			STJ010.TJ_FILIAL,
			STJ010.TJ_ORDEM,
			SCP010.CP_OP,
			SCP010.CP_NUMOS,
			SCP010.CP_NUM
	) as contador
from SCP010 (nolock)
	inner join STJ010 (nolock)
		on 	STJ010.D_E_L_E_T_ = ''
		and STJ010.TJ_FILIAL = SCP010.CP_FILIAL
		and STJ010.TJ_ORDEM = substring(SCP010.CP_OP, 1, 6)
where SCP010.D_E_L_E_T_ = ''