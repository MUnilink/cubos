select
	STJ010.TJ_FILIAL as FILIAL,
	STJ010.TJ_ORDEM as OS,
	STJ010.TJ_CODBEM as BEM,
	STL010.TL_CODIGO as COD_PRODUTO,
	STL010.TL_CUSTO as CUSTO,
	STL010.TL_QUANTID as QTD,
	STL010.TL_DTINICI as DATA,
	STL010.TL_PLANO as PLANO,
	STL010.TL_TAREFA as TAREFA
from STJ010 (nolock)
	inner join STL010 (nolock)
		on	STL010.TL_FILIAL = STJ010.TJ_FILIAL
		and STL010.TL_ORDEM = STJ010.TJ_ORDEM
		and STL010.TL_PLANO = STJ010.TJ_PLANO
where
		STJ010.D_E_L_E_T_ = ''
	and STJ010.TJ_ORDEM = '001948'
	and STL010.TL_TAREFA = '00014'
	and STL010.TL_DTINICI > 20210104