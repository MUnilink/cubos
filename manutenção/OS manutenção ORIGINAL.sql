select
	SC1010.C1_FILIAL,
	STJ010.TJ_ORDEM,
	SC1010.C1_OP,
	SCP010.CP_OP,
	substring(SC1010.C1_OP, 1, 6) NUM_OS_SC,
	substring(SCP010.CP_OP, 1, 6) NUM_OS_SA,
	SC1010.C1_NUM NUM_SC,
	SC1010.C1_ITEM ITEM_SC,
	SCP010.CP_NUM NUM_SA,
	SCP010.CP_ITEM ITEM_SA,
	SC1010.C1_PRODUTO COD_PRODUTO,
	SC1010.C1_DESCRI DESC_PRODUTO,
	SC1010.C1_UM UNIDADE,
	SC1010.C1_QUANT,
	SC1010.C1_PRECO PRECO_UNITARIO_ITEM,
	SC1010.C1_TOTAL PRECO_TOTAL,
	SC1010.C1_SEGUM UNIDADE,
	SC1010.C1_QTSEGUM,
	SC1010.C1_OBS OBS_SC,
	SC1010.C1_PEDIDO NUM_PEDIDO,
	SC1010.C1_ITEMPED ITEM_PEDIDO,
	SC1010.C1_SOLICIT SOLICITANTE_COMPRA,
	SCP010.CP_SOLICIT SOLICITANTE_ESTOQUE,
	SC1010.C1_FILENT FILIAL_ENTREGA,
	SC1010.C1_DATPRF DATA_PREVISTA,
	SC1010.C1_EMISSAO DATA_SC,
	STJ010.TJ_TERMINO STATUS_OS,
	STJ010.TJ_DTORIGI DATA_OS,
	STJ010.TJ_OBSERVA OBS_OS,
	SCP010.CP_QUJE ATENDIDA,

	row_number() over(partition by SC1010.C1_FILIAL, STJ010.TJ_ORDEM order by STJ010.TJ_ORDEM),
	count(STJ010.TJ_ORDEM) over (partition by STJ010.TJ_TERMINO) QTD_OS

from STJ010 (nolock)
	left join SC1010 (nolock)
		on SC1010.C1_FILIAL = STJ010.TJ_FILIAL
		and substring(SC1010.C1_OP, 1, 6) = STJ010.TJ_ORDEM
	inner join SCP010 (nolock)
		on SCP010.CP_FILIAL = STJ010.TJ_FILIAL
		and substring(SCP010.CP_OP, 1, 6) = STJ010.TJ_ORDEM