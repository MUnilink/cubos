select 
	TS1010.TS1_FILIAL,
	TS1010.TS1_CODBEM,
	ST9010.T9_NOME,
	ST9010.T9_ITEMCTA,
	TS1010.TS1_PLACA,
	TS1010.TS1_DOCTO,
	TS1010.TS1_QTDPAR,
	TS1010.TS1_VALOR,
	TS1010.TS1_DTEMIS,
	TS1010.TS1_DTVENC,
	TS1010.TS1_IDDOCT
from TS1010 (nolock)
	inner join ST9010 (nolock)
		on TS1010.TS1_CODBEM = ST9010.T9_CODBEM
where
		year(TS1010.TS1_DTEMIS) = 2021
	and TS1010.TS1_CODBEM in
	(
		select string_split(SE2010.E2_HIST, ' ') from SE2010
	)

