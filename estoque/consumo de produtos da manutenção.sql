        on SB9.D_E_L_E_T_ = ''
        and SB9.B9_DATA = eomonth(SD3.D3_EMISSAO)
        and SB9.B9_FILIAL = SD3.D3_FILIAL
        and SB9.B9_LOCAL = SD3.D3_LOCAL
        and SB9.B9_COD = SD3.D3_COD
