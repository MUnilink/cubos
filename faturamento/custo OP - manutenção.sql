/* QUERY PRINCIPAL DO PROCESSO DA MANUTENÇÃO */

SELECT
    STJ.TJ_CODBEM,
    ST9.T9_NOME,
    ZC2.ZC2_NUM,
    STJ.TJ_DTORIGI,
    isnull(ZC2.R_E_C_N_O_, 0) as REGZC2,
    ZC2.ZC2_QTDREA as QUANT,
    ZC2.ZC2_TOTAL,
    ST9.T9_CODBEM,
    ST9.T9_YPORTAL,    
    VALOR/(ZC2.ZC2_QTDREA from ZC2010 ) * ZC2.ZC2_QTDREA as VLUREA,
    ST6.T6_YHRPADR
FROM
(
    SELECT
        trim(STJ010.TJ_CODBEM) as TJ_CODBEM,
        SUM((STJ010.TJ_CUSTMDO + STJ010.TJ_CUSTMAT + STJ010.TJ_CUSTMAA + STJ010.TJ_CUSTMAS) /CASE WHEN STJ010.TJ_YVLD > 0 THEN STJ010.TJ_YVLD ELSE 1 END) as VALOR,
        MAX(STJ010.TJ_DTORIGI) as TJ_DTORIGI
    FROM STJ010
    WHERE
            STJ010.TJ_FILIAL = '010102'
        AND STJ010.TJ_DTORIGI BETWEEN '20230201' AND '20230228'
        AND STJ010.TJ_DTORIGI BETWEEN CASE WHEN STJ010.TJ_YVLD > 1 THEN CONVERT(VARCHAR(8), DATEADD(m, (STJ010.TJ_YVLD-1)*-1, '20230201'), 112) ELSE '20230201' END AND '20230228'
        AND STJ010.TJ_SITUACA = 'L'
        AND STJ010.D_E_L_E_T_ = ''
    GROUP BY TJ_CODBEM
) STJ
    INNER JOIN ZC2010 ZC2
        ON ZC2.D_E_L_E_T_ = ''
        AND STJ.TJ_CODBEM = ZC2.ZC2_COD
        AND ZC2.ZC2_TIPO = 3
        AND ZC2.ZC2_DATA BETWEEN '20230201' AND '20230228'
        AND ZC2.ZC2_COMPET = ''
        AND ZC2.ZC2_FILIAL = '010102'
    INNER JOIN
    (
        SELECT
            ZC2_COD TOTCOD,
            SUM(ZC2_QTDREA) TOTQTD
        FROM ZC2010 ZC2
        WHERE
                ZC2.ZC2_FILIAL = '010102'
            AND ZC2.ZC2_DATA BETWEEN '20230201' AND '20230228'
            AND ZC2.ZC2_TIPO = 3
            AND ZC2.ZC2_COMPET = ''
            AND ZC2.D_E_L_E_T_ = ''
        GROUP BY ZC2.ZC2_COD
    ) TOTZC2
        on STJ.TJ_CODBEM = TOTCOD
    INNER JOIN ST9010 ST9
        ON ST9.T9_CODBEM = STJ.TJ_CODBEM
        AND ST9.D_E_L_E_T_<>'*'
    INNER JOIN ST6010 ST6
        ON ST6.T6_CODFAMI = ST9.T9_CODFAMI
        AND ST6.D_E_L_E_T_<>'*'

/* TABELA DE LOG */
SELECT * FROM ZG1010 WHERE ZG1_TIPO = 'Manutenção' AND ZG1_ATIVO = 'S' AND D_E_L_E_T_ = ' '

/* SOMA DO CUSTO MESAL POR BEM */
SELECT STJ.TJ_CODBEM, SUM(STL.TL_CUSTO) AS CUSTOTOT
FROM STJ010 STJ
INNER JOIN STL010 STL
on STL.D_E_L_E_T_ = ''
and STL.TL_FILIAL = STJ.TJ_FILIAL
and STL.TL_PLANO = STJ.TJ_PLANO
and STL.TL_ORDEM = STJ.TJ_ORDEM
WHERE
STJ.D_E_L_E_T_<>'*'
AND STJ.TJ_DTORIGI BETWEEN '20230201' AND '20230228'
AND STL.TL_DOC <> ' '
group by STJ.TJ_CODBEM

/* SOMA DAS HORAS DE APONTAMENTO DO BEM POR MES - HORAS PRODUTIVAS */
SELECT SUM(datediff(MINUTE, concat(ZC2.ZC2_DTINI, ' ', ZC2.ZC2_HRINI), concat(ZC2.ZC2_DTFIM, ' ', ZC2.ZC2_HRFIM))/60.0) AS HrApont
FROM ZC2010 ZC2
WHERE ZC2_FILIAL='010102'
  AND ZC2_DATA BETWEEN '20230201' AND '20230228'
  AND ZC2_TIPO='3'
  AND ZC2.D_E_L_E_T_=' '
  AND (ZC2_DTINI <> ' '
       AND ZC2_DTFIM <> ' '
       AND ZC2_HRINI <> ' '
       AND ZC2_HRFIM <> ' ')
  AND ZC2_COD = 'H01'